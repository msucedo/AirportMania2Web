import { parseAwardShines, parseAwardsTable, type AwardPlace } from './awards';
import {
  parseGasStationTable,
  parseLuggageTable,
  parseGateTable,
  parseHangarTable,
  parseRunwayTable,
  type GasStationDescriptor,
  type GateDescriptor,
  type HangarDescriptor,
  type LuggageDescriptor,
  type RunwayDescriptor,
} from './airport';
import { parseLevelsDb, parseStageSchedule, type AreaInfo, type StageSchedule } from './levels';
import { parsePlaneTable, type PlaneDescriptor } from './planes';
import { Resources, type ResourcesData } from './resources';
import { Strings, type Language } from './strings';
import type { Point, XmlNode } from './xml';

export interface GameData {
  resources: Resources;
  planes: Map<number, PlaneDescriptor>;
  gates: Map<number, GateDescriptor>;
  runways: Map<number, RunwayDescriptor>;
  gasStations: Map<number, GasStationDescriptor>;
  hangars: Map<number, HangarDescriptor>;
  luggages: Map<number, LuggageDescriptor>;
  areas: Map<number, AreaInfo>;
  stage(number: number): Promise<StageSchedule>;
  /** Where each level's marker sits on the world map, in map pixels: `positions.get(stage)[level - 1]`. */
  levelPositions(): Promise<Map<number, Point[]>>;
  /** Where each award is in the awards room. */
  awards(): Promise<AwardPlace[]>;
  awardShines(): Promise<Map<number, Point[]>>;
  strings(language: Language): Promise<Strings>;
  /** The island's shore waves (`MESHES.WATER_MESH`): points with how far across the band each is, and triangles. */
  waterMesh(): Promise<{ points: number[]; across: number[]; indices: number[] }>;
}

// Generated by `npm run import-assets`; loaded lazily so a missing import fails with a clear message.
const generated = import.meta.glob<unknown>('./generated/**/*.json', { import: 'default' });

async function json<T>(rel: string): Promise<T> {
  const loader = generated[`./generated/${rel}`];
  if (!loader) throw new Error(`Missing generated data "${rel}". Run: npm run import-assets`);
  return (await loader()) as T;
}

export async function loadGameData(): Promise<GameData> {
  const [resources, planes, gates, runways, levelsDb, gasStations, hangars, luggages] = await Promise.all([
    json<ResourcesData>('resources.json'),
    json<XmlNode[]>('data/descriptors/plane_descriptor_table.json'),
    json<XmlNode[]>('data/descriptors/gate_descriptor_table.json'),
    json<XmlNode[]>('data/descriptors/runway_descriptor_table.json'),
    json<XmlNode[]>('data/descriptors/levels_db.json'),
    json<XmlNode[]>('data/descriptors/gas_station_descriptor_table.json'),
    json<XmlNode[]>('data/descriptors/hangar_descriptor_table.json'),
    json<XmlNode[]>('data/descriptors/luggage_descriptor_table.json'),
  ]);
  return {
    resources: new Resources(resources),
    planes: parsePlaneTable(planes),
    gates: parseGateTable(gates),
    runways: parseRunwayTable(runways),
    gasStations: parseGasStationTable(gasStations),
    hangars: parseHangarTable(hangars),
    luggages: parseLuggageTable(luggages),
    areas: parseLevelsDb(levelsDb),
    stage: async (number) =>
      parseStageSchedule(await json<XmlNode[]>(`data/maps/stage_levels_${String(number).padStart(2, '0')}.json`)),
    waterMesh: async () => {
      const [mesh] = await json<XmlNode[]>('data/meshes/water_mesh.json');
      const of = (tag: string): XmlNode[] => (mesh?.c ?? []).filter((node) => node.t === tag);
      return {
        points: of('Vertex').flatMap((node) => [Number(node.a.X), Number(node.a.Y)]),
        across: of('Vertex').map((node) => Number(node.a.V)),
        indices: of('Index').map((node) => Number(node.a.Value)),
      };
    },
    awardShines: async () => parseAwardShines(await json<XmlNode[]>('data/descriptors/awards_room_descriptor_table.json')),
    awards: async () => parseAwardsTable(await json<XmlNode[]>('data/descriptors/awards_room_descriptor_table.json')),
    levelPositions: async () => {
      const table = new Map<number, Point[]>();
      // The table lists some levels twice; the entries agree.
      for (const node of await json<XmlNode[]>('data/descriptors/levels_position.json')) {
        if (node.t !== 'Level') continue;
        const levels = table.get(Number(node.a.StageNumber)) ?? [];
        levels[Number(node.a.LevelNumber) - 1] = { x: Number.parseFloat(node.a.X!), y: Number.parseFloat(node.a.Y!) };
        table.set(Number(node.a.StageNumber), levels);
      }
      return table;
    },
    strings: async (language) => new Strings(language, await json<Record<string, string>>(`data/languages/${language}.json`)),
  };
}
